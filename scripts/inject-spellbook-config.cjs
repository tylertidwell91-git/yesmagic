#!/usr/bin/env node
/**
 * Writes public/spellbook/config.js for The Spellbook (Supabase URL + anon key).
 * Reads SPELLBOOK_SUPABASE_URL and SPELLBOOK_SUPABASE_ANON_KEY from the environment,
 * or from yesmagic/.env then .env.production (first line wins for unset env).
 */
const { writeFileSync, mkdirSync, readFileSync, existsSync } = require("fs")
const { join } = require("path")

const root = join(__dirname, "..")
const outDir = join(root, "public", "spellbook")

function loadDotenvFile(rel) {
  const p = join(root, rel)
  if (!existsSync(p)) return
  const text = readFileSync(p, "utf8")
  for (const line of text.split("\n")) {
    const t = line.trim()
    if (!t || t.startsWith("#")) continue
    const eq = t.indexOf("=")
    if (eq <= 0) continue
    const key = t.slice(0, eq).trim()
    let val = t.slice(eq + 1).trim()
    if (
      (val.startsWith('"') && val.endsWith('"')) ||
      (val.startsWith("'") && val.endsWith("'"))
    ) {
      val = val.slice(1, -1)
    }
    if (process.env[key] === undefined || process.env[key] === "") {
      process.env[key] = val
    }
  }
}

loadDotenvFile(".env")
loadDotenvFile(".env.production")

function normalizeSpellbookSupabaseUrl(raw) {
  let u = String(raw || "").trim()
  if (
    (u.startsWith('"') && u.endsWith('"')) ||
    (u.startsWith("'") && u.endsWith("'"))
  ) {
    u = u.slice(1, -1).trim()
  }
  // Pasting the REST or Auth API path breaks sign-in (invalid request URL).
  u = u.replace(/\/?(rest\/v1|auth\/v1|storage\/v1|graphql\/v1)\/?$/i, "")
  u = u.replace(/\/+$/, "")
  if (!u) return ""
  if (!/^https:\/\//i.test(u)) {
    if (/^http:\/\//i.test(u)) u = u.replace(/^http/i, "https")
    else u = "https://" + u.replace(/^\/+/, "")
  }
  return u
}

function normalizeSpellbookAnonKey(raw) {
  let k = String(raw || "").trim()
  if (
    (k.startsWith('"') && k.endsWith('"')) ||
    (k.startsWith("'") && k.endsWith("'"))
  ) {
    k = k.slice(1, -1).trim()
  }
  return k
}

const url = normalizeSpellbookSupabaseUrl(process.env.SPELLBOOK_SUPABASE_URL || "")
const key = normalizeSpellbookAnonKey(process.env.SPELLBOOK_SUPABASE_ANON_KEY || "")

function normalizeNotifyBase(raw) {
  let b = String(raw || "").trim()
  if (
    (b.startsWith('"') && b.endsWith('"')) ||
    (b.startsWith("'") && b.endsWith("'"))
  ) {
    b = b.slice(1, -1).trim()
  }
  b = b.replace(/\/+$/, "")
  return b
}

const notifyBase = normalizeNotifyBase(process.env.SPELLBOOK_TRADE_NOTIFY_BASE || "")

mkdirSync(outDir, { recursive: true })
const content = `/* Generated by scripts/inject-spellbook-config.cjs — do not edit. */
window.SPELLBOOK_SUPABASE_URL = ${JSON.stringify(url)};
window.SPELLBOOK_SUPABASE_ANON_KEY = ${JSON.stringify(key)};
window.SPELLBOOK_TRADE_NOTIFY_BASE = ${JSON.stringify(notifyBase)};
`
writeFileSync(join(outDir, "config.js"), content, "utf8")
console.log(
  "[spellbook] Wrote public/spellbook/config.js — SPELLBOOK_SUPABASE_URL: " +
    (url ? "set" : "EMPTY") +
    " | SPELLBOOK_SUPABASE_ANON_KEY: " +
    (key ? "set" : "EMPTY")
)
if (!url || !key) {
  console.warn(
    "[spellbook] Netlify: open each variable → ensure scope includes Builds (not only Functions). Redeploy after saving."
  )
}
